"""
Overnight build orchestrator for Reel Blocker — ONE FILE PER CALL edition.

Why one file per call:
  A 14B local model can't hold a multi-step scope ("implement steps 10-16") or a
  hard negative constraint across a long tool-call sequence — it overreaches,
  builds the whole project at once, and reintroduces banned syntax. So we shrink
  the unit of work to a SINGLE file per model call, with:
    - a focused per-file spec (pointing at the exact CLAUDE.md section),
    - a SCOPE GUARD that discards anything the model touches outside that one
      file (so overreach becomes harmless),
    - the deterministic verify.sh + behavioral invariants as the gate,
    - files a 14B can't make (PNG icons, the exact YouTube stub) generated by the
      harness with NO model call.

Everything else (preflight, timeouts, escalation, no-op detection, clean-slate
retries, review pass, git tags, auto-resume, run_state/report, circuit breaker)
carries over from the previous design.

Required env:
  export ANTHROPIC_BASE_URL=http://127.0.0.1:1234
  export ANTHROPIC_API_KEY=lm-studio
  export ANTHROPIC_MODEL=qwen3-14b

Optional env:
  RB_RUN_HOURS=0           global wall-clock budget; 0 = no deadline (Ctrl+C stops)
  RB_PRIMARY_TIMEOUT=1200  seconds per primary (one-file) call
  RB_FIX_TIMEOUT=600       seconds per fix call
  RB_REVIEW_TIMEOUT=600    seconds per review call

Usage:
  python3 orchestrator.py                 # run/resume all remaining stages
  python3 orchestrator.py --dry-run       # list the stages and prompts
  python3 orchestrator.py --from-stage=12 # pin start (overrides tag auto-resume)
  python3 orchestrator.py --no-review     # skip the (already optional) review pass
  python3 orchestrator.py --skip-preflight

Resume: with no --from-stage, the run auto-resumes after the highest verified
`stage-N` git tag. Per-call timeouts always apply, so a hung call can't stall the
run even with no global deadline.
"""

# --- deterministic post-processor ----------------------------------------
def strip_module_syntax(repo):
    """Fix the module-syntax mistakes a 14B makes repeatedly, so we don't spend a
    model call on what a regex handles for free. Now also covers the block forms
    `export { ... };` and `export default ...` that slipped through before."""
    changed = []
    for d in (repo / "content", repo / "background"):
        if not d.exists():
            continue
        for f in d.rglob("*.js"):
            text = original = f.read_text(encoding="utf-8")
            text = re.sub(r"^import\s+[\w{},\s*]+\s+from\s+['\"].*?['\"];?\s*$", "",
                          text, flags=re.MULTILINE)
            text = re.sub(r"^(?:const|let|var)\s+\w+\s*=\s*require\s*\([^)]+\);?\s*$", "",
                          text, flags=re.MULTILINE)
            # named-export block:  export { a, b, c };  -> drop entirely
            text = re.sub(r"^export\s*\{[^}]*\}\s*;?\s*$", "", text, flags=re.MULTILINE)
            # export default <expr>;  -> drop the `export default ` lead-in
            text = re.sub(r"^export\s+default\s+", "", text, flags=re.MULTILINE)
            # module.exports = ...;   -> drop
            text = re.sub(r"^\s*module\.exports\s*=.*$", "", text, flags=re.MULTILINE)
            text = re.sub(r"^export\s+function\s+(\w+)\s*\(",
                          r"window.RB.\1 = function(", text, flags=re.MULTILINE)
            text = re.sub(r"^export\s+(?:const|let|var)\s+(\w+)\s*=",
                          r"window.RB.\1 =", text, flags=re.MULTILINE)
            if text != original:
                f.write_text(text, encoding="utf-8")
                changed.append(str(f.relative_to(repo)))
    if changed:
        print(f"  [post-process] fixed module syntax in: {', '.join(changed)}")


# --- git helpers ----------------------------------------------------------
def git(repo, *args, check=False, capture=False):
    return subprocess.run(["git", *args], cwd=repo, check=check, text=True,
                          stdout=subprocess.PIPE if capture else None,
                          stderr=subprocess.STDOUT if capture else None)

def head(repo):
    return (git(repo, "rev-parse", "HEAD", capture=True).stdout or "").strip()

def reset_clean(repo, ref):
    git(repo, "reset", "--hard", ref)
    git(repo, "clean", "-fd")

def in_baseline(repo, baseline, path):
    r = subprocess.run(["git", "cat-file", "-e", f"{baseline}:{path}"], cwd=repo,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return r.returncode == 0

def scope_guard(repo, baseline, allowed):
    """The core of one-file-per-call: after a model call, neutralise any model
    commits and discard EVERY change outside the allowed file set, so the model
    physically cannot affect other files. Leaves working tree = baseline + allowed
    changes."""
    allowed = set(allowed)
    git(repo, "reset", "--mixed", baseline)  # undo model commits, keep worktree
    r = git(repo, "status", "--porcelain", capture=True)
    reverted = []
    for line in (r.stdout or "").splitlines():
        path = line[3:]
        if " -> " in path:           # rename: keep the destination path
            path = path.split(" -> ", 1)[1]
        path = path.strip().strip('"')
        if not path or path in allowed:
            continue
        if in_baseline(repo, baseline, path):
            git(repo, "checkout", baseline, "--", path)
        else:
            try: (repo / path).unlink()
            except OSError: pass
        reverted.append(path)
    if reverted:
        uniq = sorted(set(reverted))
        print(f"  [scope] discarded out-of-scope changes: {', '.join(uniq[:8])}"
              + (" ..." if len(uniq) > 8 else ""))
    return reverted

def worktree_signature(repo, baseline):
    git(repo, "add", "-A")
    r = git(repo, "diff", "--cached", baseline, capture=True)
    sig = hashlib.sha1((r.stdout or "").encode("utf-8", "replace")).hexdigest()
    git(repo, "reset", "-q")
    return sig

def stage_diff(repo, baseline, budget=DIFF_BUDGET):
    git(repo, "add", "-A")
    r = git(repo, "diff", "--cached", baseline, capture=True)
    git(repo, "reset", "-q")
    d = r.stdout or ""
    return d if len(d) <= budget else d[:budget] + f"\n... [diff truncated] ..."

def highest_stage_tag(repo):
    r = git(repo, "tag", "--list", "stage-*", capture=True)
    best = 0
    for line in (r.stdout or "").splitlines():
        m = re.match(r"stage-(\d+)$", line.strip())
        if m: best = max(best, int(m.group(1)))
    return best


# --- scripted file generators (no model call) ----------------------------
def _write_png(path, n, rgb=(17, 17, 17)):
    """Minimal valid solid-colour RGB PNG, dependency-free."""
    def chunk(typ, data):
        return (struct.pack(">I", len(data)) + typ + data +
                struct.pack(">I", zlib.crc32(typ + data) & 0xffffffff))
    ihdr = struct.pack(">IIBBBBB", n, n, 8, 2, 0, 0, 0)  # 8-bit truecolour
    row = b"\x00" + bytes(rgb) * n
    idat = zlib.compress(row * n, 9)
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) +
           chunk(b"IDAT", idat) + chunk(b"IEND", b""))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)

